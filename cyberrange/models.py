"""What the site records about the engagement days.

Finding          a Red team's report against a cell in its scope
                 (contract: jengasec-cyberrange-infrastructure/contracts/findings.md, AIC-16)
WireGuardProfile one person's WireGuard configuration, downloadable only by them
                 (generated by NET's scripts/make-wg-configs.py, AIC-16 / NET-11)
"""
import re
import uuid

from django.conf import settings
from django.core.exceptions import ValidationError
from django.db import models
from django.utils import timezone

# Three rounds, one per engagement day (ADR 0004).
ROUND_CHOICES = [(1, "Day 1"), (2, "Day 2"), (3, "Day 3")]


class Finding(models.Model):
    class Status(models.TextChoices):
        SUBMITTED = "submitted", "Submitted"
        VALID = "valid", "Valid"
        DUPLICATE = "duplicate", "Duplicate"
        INVALID = "invalid", "Invalid"
        OUT_OF_SCOPE = "out_of_scope", "Out of scope"

    class Severity(models.TextChoices):
        # Set by the judges, never by the reporter (findings contract).
        LOW = "low", "Low"
        MEDIUM = "medium", "Medium"
        HIGH = "high", "High"
        CRITICAL = "critical", "Critical"

    competition = models.ForeignKey(
        "competitions.Competition", on_delete=models.CASCADE, related_name="findings"
    )
    red_team = models.ForeignKey(
        "accounts.Team", on_delete=models.CASCADE, related_name="findings_reported"
    )
    target_team = models.ForeignKey(
        "accounts.Team", on_delete=models.CASCADE, related_name="findings_against"
    )
    round = models.PositiveSmallIntegerField(choices=ROUND_CHOICES)
    started_at = models.DateTimeField(help_text="Platform clock, when the attack started.")
    ended_at = models.DateTimeField(help_text="Platform clock, when it ended.")
    title = models.CharField(max_length=200, help_text="One line: what is wrong.")
    technique = models.CharField(max_length=200, help_text="Class of issue, e.g. IDOR, SQL injection.")
    attack_id = models.CharField(
        max_length=20, blank=True, help_text="MITRE ATT&CK technique ID, where one fits (e.g. T1190)."
    )
    steps = models.TextField(help_text="Numbered steps, enough for a judge to repeat it.")
    evidence = models.TextField(
        help_text="Requests and responses, telemetry event IDs, or what the attached file shows."
    )
    telemetry_event_ids = models.JSONField(
        default=list,
        blank=True,
        help_text="Stable evt_ identifiers cited by this finding; no request or response bodies.",
    )
    correlation_ids = models.JSONField(
        default=list,
        blank=True,
        help_text="Opaque request or trace identifiers cited by this finding.",
    )
    evidence_file = models.FileField(upload_to="range/evidence/%Y/%m/", blank=True)
    impact = models.TextField(help_text="What an attacker gains: data, access, availability.")
    suggested_fix = models.TextField(blank=True)

    status = models.CharField(max_length=15, choices=Status.choices, default=Status.SUBMITTED)
    severity = models.CharField(max_length=10, choices=Severity.choices, blank=True)
    duplicate_of = models.ForeignKey(
        "self", null=True, blank=True, on_delete=models.SET_NULL, related_name="duplicates"
    )
    reviewer_notes = models.TextField(blank=True)

    submitted_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="findings"
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        # First valid report wins, so submission order is the natural order.
        ordering = ["created_at", "pk"]
        indexes = [models.Index(fields=["competition", "round", "target_team"], name="ix_finding_round_target")]

    def __str__(self):
        return f"{self.red_team.cell_id or self.red_team.team_name} → {self.target_team.cell_label}: {self.title}"

    def clean(self):
        if self.started_at and self.ended_at and self.ended_at < self.started_at:
            raise ValidationError({"ended_at": "The end time is before the start time."})
        for field, pattern in (
            ("telemetry_event_ids", r"evt_[a-f0-9]{64}"),
            ("correlation_ids", r"[A-Za-z0-9][A-Za-z0-9._:/-]{0,127}"),
        ):
            values = getattr(self, field)
            if not isinstance(values, list) or any(
                not isinstance(value, str) or not re.fullmatch(pattern, value)
                for value in values
            ):
                raise ValidationError({field: "Use a list of valid opaque identifiers."})
            if len(values) != len(set(values)):
                raise ValidationError({field: "Each identifier may appear only once."})


class RangeApplication(models.Model):
    """One canonical application instance in ENT-A or ENT-B."""

    class Enterprise(models.TextChoices):
        A = "ENT-A", "ENT-A"
        B = "ENT-B", "ENT-B"

    class Status(models.TextChoices):
        BUILDING = "building", "Building"
        FROZEN = "frozen", "Frozen"
        LIVE = "live", "Live"
        DOWN = "down", "Down"

    competition = models.ForeignKey(
        "competitions.Competition", on_delete=models.CASCADE, related_name="range_applications"
    )
    application_instance_id = models.CharField(max_length=11)
    enterprise = models.CharField(max_length=5, choices=Enterprise.choices)
    application = models.CharField(max_length=5)
    namespace = models.CharField(max_length=80)
    service_name = models.CharField(max_length=200)
    ip_address = models.GenericIPAddressField()
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.BUILDING)
    optional = models.BooleanField(default=False)
    enabled = models.BooleanField(default=True)
    image_digest = models.CharField(
        max_length=71,
        blank=True,
        help_text="Immutable sha256 image digest; empty until the application is frozen.",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "applications"
        ordering = ["enterprise", "application"]
        constraints = [
            models.UniqueConstraint(
                fields=["competition", "application_instance_id"],
                name="unique_application_instance",
            ),
            models.UniqueConstraint(
                fields=["competition", "namespace"], name="unique_application_namespace"
            ),
            models.UniqueConstraint(
                fields=["competition", "ip_address"], name="unique_application_ip"
            ),
        ]

    def __str__(self):
        return self.application_instance_id

    def clean(self):
        expected_id = f"{self.enterprise}/{self.application}"
        expected_namespace = f"jengasec-{self.enterprise.lower()}-{self.application.lower()}"
        if self.application_instance_id != expected_id:
            raise ValidationError({"application_instance_id": f"Expected {expected_id}."})
        if self.namespace != expected_namespace:
            raise ValidationError({"namespace": f"Expected {expected_namespace}."})
        if self.application not in {f"APP{number:02d}" for number in range(1, 10)}:
            raise ValidationError({"application": "Expected APP01 through APP09."})


class IPAllocation(models.Model):
    """Time-bounded attribution for a participant or application address."""

    class Kind(models.TextChoices):
        PARTICIPANT = "participant", "Participant"
        APPLICATION = "application", "Application"
        SPARE = "spare", "Spare"

    class TeamLabel(models.TextChoices):
        RED_APP = "red-app", "Red application"
        BLUE_APP = "blue-app", "Blue application"
        RED_AI = "red-ai", "Red AI"
        BLUE_AI = "blue-ai", "Blue AI"
        STAFF = "staff", "Staff"
        JUDGE = "judge", "Judge"

    class Status(models.TextChoices):
        RESERVED = "reserved", "Reserved"
        ACTIVE = "active", "Active"
        REVOKED = "revoked", "Revoked"

    allocation_id = models.UUIDField(default=uuid.uuid4, editable=False, unique=True)
    competition = models.ForeignKey(
        "competitions.Competition", on_delete=models.CASCADE, related_name="ip_allocations"
    )
    ip_address = models.GenericIPAddressField()
    kind = models.CharField(max_length=12, choices=Kind.choices)
    participant = models.ForeignKey(
        "accounts.UserProfile",
        null=True,
        blank=True,
        on_delete=models.PROTECT,
        related_name="ip_allocations",
    )
    team = models.ForeignKey(
        "accounts.Team",
        null=True,
        blank=True,
        on_delete=models.PROTECT,
        related_name="ip_allocations",
    )
    team_label = models.CharField(max_length=10, choices=TeamLabel.choices, blank=True)
    namespace = models.CharField(max_length=80, blank=True)
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.RESERVED)
    valid_from = models.DateTimeField(default=timezone.now)
    valid_until = models.DateTimeField(null=True, blank=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "ip_allocations"
        ordering = ["ip_address"]
        constraints = [
            models.UniqueConstraint(
                fields=["competition", "ip_address"], name="unique_competition_ip_allocation"
            )
        ]

    def clean(self):
        if self.kind == self.Kind.PARTICIPANT and not self.participant_id:
            raise ValidationError({"participant": "Participant allocations require a profile."})
        if self.valid_until and self.valid_until < self.valid_from:
            raise ValidationError({"valid_until": "Must not precede valid_from."})


class ScopeAssignment(models.Model):
    """A participant network allowed to reach one application instance."""

    competition = models.ForeignKey(
        "competitions.Competition", on_delete=models.CASCADE, related_name="range_scopes"
    )
    target_assignment = models.OneToOneField(
        "competitions.TargetAssignment",
        on_delete=models.CASCADE,
        related_name="range_scope",
    )
    team = models.ForeignKey(
        "accounts.Team", on_delete=models.PROTECT, related_name="range_scopes"
    )
    source_cidr = models.CharField(max_length=43)
    application = models.ForeignKey(
        RangeApplication, on_delete=models.PROTECT, related_name="scope_assignments"
    )
    active = models.BooleanField(default=False)
    valid_from = models.DateTimeField(default=timezone.now)
    valid_until = models.DateTimeField(null=True, blank=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "scope_assignments"
        ordering = ["team__team_identifier", "application__application_instance_id"]

    def clean(self):
        if self.team_id and self.competition_id != self.team.competition_id:
            raise ValidationError({"team": "Team belongs to a different competition."})
        if self.application_id and self.competition_id != self.application.competition_id:
            raise ValidationError({"application": "Application belongs to a different competition."})
        if self.valid_until and self.valid_until < self.valid_from:
            raise ValidationError({"valid_until": "Must not precede valid_from."})


class WireGuardProfile(models.Model):
    """One person's WireGuard configuration.

    It holds a private key, so it is never linked publicly: the only way out
    is `cyberrange:wireguard_download`, for its owner, and every download
    is audited. Loaded by `manage.py load_wireguard_profiles`.
    """

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="wireguard_profile"
    )
    team = models.ForeignKey(
        "accounts.Team", null=True, blank=True, on_delete=models.SET_NULL, related_name="wireguard_profiles"
    )
    address = models.CharField(max_length=43, blank=True, help_text="Tunnel address, e.g. 10.60.3.7/32.")
    config = models.FileField(upload_to="range/wireguard/")
    active = models.BooleanField(default=False)
    last_handshake_at = models.DateTimeField(null=True, blank=True)
    issued_at = models.DateTimeField(auto_now_add=True)
    downloaded_at = models.DateTimeField(null=True, blank=True)
    revoked = models.BooleanField(default=False, help_text="Revoked at teardown (SEC-15).")

    class Meta:
        ordering = ["user__username"]

    def __str__(self):
        return f"WireGuard profile for {self.user}"
