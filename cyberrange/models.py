"""What the site records about the engagement days.

Finding          a Red team's report against a cell in its scope
                 (contract: jengasec-cyberrange-infrastructure/contracts/findings.md, AIC-16)
WireGuardProfile one person's WireGuard configuration, downloadable only by them
                 (generated by NET's scripts/make-wg-configs.py, AIC-16 / NET-11)
"""
from django.conf import settings
from django.core.exceptions import ValidationError
from django.db import models

# Three rounds, one per engagement day (ADR 0004).
ROUND_CHOICES = [(1, "Day 1"), (2, "Day 2"), (3, "Day 3")]


class Finding(models.Model):
    class Status(models.TextChoices):
        SUBMITTED = "submitted", "Submitted"
        VALID = "valid", "Valid"
        DUPLICATE = "duplicate", "Duplicate"
        INVALID = "invalid", "Invalid"
        OUT_OF_SCOPE = "out_of_scope", "Out of scope"

    class Severity(models.TextChoices):
        # Set by the judges, never by the reporter (findings contract).
        LOW = "low", "Low"
        MEDIUM = "medium", "Medium"
        HIGH = "high", "High"
        CRITICAL = "critical", "Critical"

    competition = models.ForeignKey(
        "competitions.Competition", on_delete=models.CASCADE, related_name="findings"
    )
    red_team = models.ForeignKey(
        "accounts.Team", on_delete=models.CASCADE, related_name="findings_reported"
    )
    target_team = models.ForeignKey(
        "accounts.Team", on_delete=models.CASCADE, related_name="findings_against"
    )
    round = models.PositiveSmallIntegerField(choices=ROUND_CHOICES)
    started_at = models.DateTimeField(help_text="Platform clock, when the attack started.")
    ended_at = models.DateTimeField(help_text="Platform clock, when it ended.")
    title = models.CharField(max_length=200, help_text="One line: what is wrong.")
    technique = models.CharField(max_length=200, help_text="Class of issue, e.g. IDOR, SQL injection.")
    attack_id = models.CharField(
        max_length=20, blank=True, help_text="MITRE ATT&CK technique ID, where one fits (e.g. T1190)."
    )
    steps = models.TextField(help_text="Numbered steps, enough for a judge to repeat it.")
    evidence = models.TextField(
        help_text="Requests and responses, telemetry event IDs, or what the attached file shows."
    )
    evidence_file = models.FileField(upload_to="range/evidence/%Y/%m/", blank=True)
    impact = models.TextField(help_text="What an attacker gains: data, access, availability.")
    suggested_fix = models.TextField(blank=True)

    status = models.CharField(max_length=15, choices=Status.choices, default=Status.SUBMITTED)
    severity = models.CharField(max_length=10, choices=Severity.choices, blank=True)
    duplicate_of = models.ForeignKey(
        "self", null=True, blank=True, on_delete=models.SET_NULL, related_name="duplicates"
    )
    reviewer_notes = models.TextField(blank=True)

    submitted_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="findings"
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        # First valid report wins, so submission order is the natural order.
        ordering = ["created_at", "pk"]
        indexes = [models.Index(fields=["competition", "round", "target_team"], name="ix_finding_round_target")]

    def __str__(self):
        return f"{self.red_team.cell_id or self.red_team.team_name} → {self.target_team.cell_label}: {self.title}"

    def clean(self):
        if self.started_at and self.ended_at and self.ended_at < self.started_at:
            raise ValidationError({"ended_at": "The end time is before the start time."})


class VpnRegistration(models.Model):
    """One person's registration with NET's WireGuard control plane.

    Holds only the public key: the private key is made and kept by the
    WireGuard app on the person's own device. `services/vpn_portal.py`
    talks to the control plane.
    """

    class Status(models.TextChoices):
        APPROVED = "approved", "Registered"
        FAILED = "failed", "Failed"
        REVOKED = "revoked", "Revoked"

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="vpn_registration"
    )
    team = models.ForeignKey(
        "accounts.Team", null=True, blank=True, on_delete=models.SET_NULL, related_name="vpn_registrations"
    )
    role = models.CharField(max_length=32)
    team_code = models.CharField(max_length=20, blank=True, help_text="NET's team code, e.g. RED-APP-07.")
    public_key = models.CharField(max_length=44)
    # Sent to NET as external_identity. Bumped after a revocation, because NET
    # never reuses an identity.
    attempt = models.PositiveSmallIntegerField(default=1)
    participant_id = models.PositiveIntegerField(null=True, blank=True)
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.FAILED)
    last_error = models.CharField(max_length=300, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["user__username"]

    def __str__(self):
        return f"VPN registration for {self.user}"

    @property
    def external_identity(self):
        return f"jengasec-web-{self.user_id}-{self.attempt}"


class WireGuardProfile(models.Model):
    """One person's WireGuard configuration.

    It holds a private key, so it is never linked publicly: the only way out
    is `cyberrange:wireguard_download`, for its owner, and every download
    is audited. Loaded by `manage.py load_wireguard_profiles`.
    """

    user = models.OneToOneField(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="wireguard_profile"
    )
    team = models.ForeignKey(
        "accounts.Team", null=True, blank=True, on_delete=models.SET_NULL, related_name="wireguard_profiles"
    )
    address = models.CharField(max_length=43, blank=True, help_text="Tunnel address, e.g. 10.60.3.7/32.")
    config = models.FileField(upload_to="range/wireguard/")
    active = models.BooleanField(default=False)
    last_handshake_at = models.DateTimeField(null=True, blank=True)
    issued_at = models.DateTimeField(auto_now_add=True)
    downloaded_at = models.DateTimeField(null=True, blank=True)
    revoked = models.BooleanField(default=False, help_text="Revoked at teardown (SEC-15).")

    class Meta:
        ordering = ["user__username"]

    def __str__(self):
        return f"WireGuard profile for {self.user}"
